#!/usr/bin/env python3
"""Render the execution-commitments table from the frozen commitments evidence.

Reads release/experiments/execution_commitments/*.commitments.json and emits a LaTeX and a
Markdown table. It only formats already-frozen records; it does not recompute them.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DIR = PROJECT_ROOT / "release" / "experiments" / "execution_commitments"
DEFAULT_CAMPAIGNS = ("C0010", "C0026", "C0045")

HEADERS = ("Campaign", "Steps", "Mechanism", "Binding", "Total commitments", "Pruned")


def _load(directory: Path, campaign_id: str) -> dict:
    return json.loads(
        (directory / f"{campaign_id}.commitments.json").read_text(encoding="utf-8")
    )


def _cells(record: dict) -> list[str]:
    return [
        record["campaign_id"],
        str(record["steps"]),
        str(record["mechanism_commitments"]),
        str(record["binding_commitments"]),
        str(record["total_execution_commitments"]),
        str(record["candidates_pruned_by_verifier"]),
    ]


def _totals(records: list[dict]) -> list[str]:
    keys = ("steps", "mechanism_commitments", "binding_commitments",
            "total_execution_commitments", "candidates_pruned_by_verifier")
    sums = {key: sum(record[key] for record in records) for key in keys}
    return ["Total", *[str(sums[key]) for key in keys]]


def render_latex(records: list[dict]) -> str:
    lines = [
        "% Generated by scripts/render_execution_commitments_table.py from frozen evidence.",
        "% Counts of explicit execution commitments, not analyst time.",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        r"\textbf{Campaign} & \textbf{Steps} & \textbf{Mechanism} & \textbf{Binding} & \textbf{Total} & \textbf{Pruned} \\",
        "\\midrule",
    ]
    lines += [" & ".join(_cells(record)) + " \\\\" for record in records]
    lines += ["\\midrule", " & ".join(_totals(records)) + " \\\\", "\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def render_markdown(records: list[dict]) -> str:
    lines = [
        "<!-- Generated from frozen execution-commitments evidence. Commitment counts, not analyst time. -->",
        "| " + " | ".join(HEADERS) + " |",
        "|" + "|".join(["---"] * len(HEADERS)) + "|",
    ]
    lines += ["| " + " | ".join(_cells(record)) + " |" for record in records]
    lines.append("| " + " | ".join(_totals(records)) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaigns", nargs="+", default=list(DEFAULT_CAMPAIGNS))
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args()

    records = [_load(args.input_dir, campaign_id) for campaign_id in args.campaigns]
    (args.output_dir / "commitments_table.tex").write_text(render_latex(records), encoding="utf-8")
    (args.output_dir / "commitments_table.md").write_text(render_markdown(records), encoding="utf-8")
    print(render_markdown(records))
    print(f"[commitments-table] wrote commitments_table.tex and commitments_table.md to {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
