#!/usr/bin/env python3
"""Render the manuscript's compact claim-to-evidence index from the ledger."""

from __future__ import annotations

import json
import sys
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = PROJECT_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from evaluation.claim_ledger import Claim, verify_ledger  # noqa: E402

LEDGER = PROJECT_ROOT / "release" / "claims" / "ledger.json"
OUTPUT = PROJECT_ROOT / "release" / "claims" / "claim_ledger_table.tex"


def _escape(value: str) -> str:
    """Escape LaTeX specials so ledger prose cannot break the generated table.

    An unescaped ampersand ends the table cell, so a value such as "ATT&CK technique"
    silently produces an extra alignment tab rather than a visible error.
    """
    for character, replacement in (
        ("\\", "\\textbackslash{}"),
        ("&", "\\&"),
        ("%", "\\%"),
        ("$", "\\$"),
        ("#", "\\#"),
        ("_", "\\_"),
        ("{", "\\{"),
        ("}", "\\}"),
        ("~", "\\textasciitilde{}"),
        ("^", "\\textasciicircum{}"),
    ):
        value = value.replace(character, replacement)
    return value


def population_description(unit: str, population: str) -> str:
    """Include the unit once when the population already declares it."""
    if population == unit or population.startswith(f"{unit}; "):
        return population
    return f"{unit}; {population}"


def main() -> int:
    payload = json.loads(LEDGER.read_text(encoding="utf-8"))
    registered = [Claim.model_validate(claim) for claim in payload["claims"]]
    verification = {
        item.claim_id: item
        for item in verify_ledger(PROJECT_ROOT, registered).verifications
    }
    claims = [
        claim.model_dump(mode="json")
        for claim in registered
        if verification[claim.claim_id].paper_ready
    ]
    lines = [
        "% Generated by scripts/render_claim_ledger_table.py from the claim ledger.",
        "\\begin{tabularx}{\\columnwidth}{@{}llL@{}}",
        "\\toprule",
        r"\textbf{Property} & \textbf{Evidence type} & "
        r"\textbf{Unit and evaluated population} \\",
        "\\midrule",
    ]
    for claim in claims:
        claim_id = claim["claim_id"].removeprefix("STICKS-")
        support_type = claim["support_type"].replace("_", " ")
        unit = claim.get("unit_of_analysis") or "not applicable"
        population = (
            claim.get("table_population") or claim.get("population") or "not applicable"
        )
        lines.append(
            f"{_escape(claim_id)} & {_escape(support_type)} & "
            f"{_escape(population_description(unit, population))} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabularx}"])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[claim-ledger-table] wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
