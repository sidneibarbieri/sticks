#!/usr/bin/env python3
"""Render the provenance table from the frozen provenance evidence.

Reads release/experiments/provenance/*.provenance.json and emits a LaTeX table and a
Markdown table. The paper includes the generated table; this script does not recompute the
provenance -- it only formats the already-frozen records.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DIR = PROJECT_ROOT / "release" / "experiments" / "provenance"
DEFAULT_CAMPAIGNS = ("C0010", "C0026", "C0045")


def _load(directory: Path, campaign_id: str) -> dict:
    return json.loads(
        (directory / f"{campaign_id}.provenance.json").read_text(encoding="utf-8")
    )


def _percent(numerator: int, denominator: int) -> str:
    return f"{(numerator / denominator if denominator else 0.0) * 100:.0f}\\%"


def _row_cells(record: dict) -> list[str]:
    occ = record["binding_occurrence_counts"]
    total = record["total_binding_occurrences"]
    return [
        record["campaign_id"],
        str(record["total_steps"]),
        str(total),
        _percent(occ["cti_evidenced"], total),
        _percent(occ["environment_determined"], total),
        _percent(occ["system_introduced"], total),
        _percent(record["mechanism_counts"]["proposer_chosen"], record["total_steps"]),
    ]


HEADERS = (
    "Campaign", "Steps", "Bindings", "CTI", "Environment", "System-introduced",
    "Proposer-chosen mech.",
)


def render_latex(records: list[dict]) -> str:
    lines = [
        "% Generated by scripts/render_provenance_table.py from frozen provenance evidence.",
        "% Binding shares use binding occurrences; mechanism share uses steps. Taxonomy version "
        f"{records[0]['taxonomy_version']} (see TAXONOMY.md).",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        r"\textbf{Campaign} & \textbf{Steps} & \textbf{Bindings} & \textbf{CTI} & "
        r"\textbf{Env.} & \textbf{Sys.-intro.} & "
        r"\textbf{\shortstack{Prop.-chosen\\mechanism}} \\",
        "\\midrule",
    ]
    for record in records:
        cells = _row_cells(record)
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def render_markdown(records: list[dict]) -> str:
    lines = [
        f"<!-- Generated from frozen provenance evidence; taxonomy v{records[0]['taxonomy_version']}. "
        "Binding shares use binding occurrences; mechanism share uses steps. -->",
        "| " + " | ".join(HEADERS) + " |",
        "|" + "|".join(["---"] * len(HEADERS)) + "|",
    ]
    for record in records:
        lines.append("| " + " | ".join(_row_cells(record)).replace("\\%", "%") + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaigns", nargs="+", default=list(DEFAULT_CAMPAIGNS))
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args()

    records = [_load(args.input_dir, campaign_id) for campaign_id in args.campaigns]
    latex_path = args.output_dir / "provenance_table.tex"
    markdown_path = args.output_dir / "provenance_table.md"
    latex_path.write_text(render_latex(records), encoding="utf-8")
    markdown_path.write_text(render_markdown(records), encoding="utf-8")
    print(render_markdown(records))
    print(f"[provenance-table] wrote {latex_path} and {markdown_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
