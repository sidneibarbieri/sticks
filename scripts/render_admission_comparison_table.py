#!/usr/bin/env python3
"""Render the admission comparison table and macros from frozen analysis records.

The table is organized as a design space rather than a list of systems: each row states which
representation an arm received and whether the deterministic verifier decided admission, so the
reader can see that contract admission moves with the gate, not the representation.
The admitted arm is checked with the same predicate that gated it, so its 1.000
rate is a consistency check rather than independent execution validation.

Every number is read from the frozen analysis records. Nothing here is typed by hand.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
COMPARISON_ROOT = PROJECT_ROOT / "release" / "experiments" / "controlled_comparison"
MACROS_OUTPUT = PROJECT_ROOT / "release" / "admission_macros.tex"

ARM_DESIGN = {
    "prior_work_style": ("raw", "no"),
    "sticks_without_admission": ("enriched", "no"),
    "sticks_admitted": ("enriched", "yes"),
}
ARM_LABEL = {
    "prior_work_style": "Raw",
    "sticks_without_admission": "Procedural",
    "sticks_admitted": "Procedural",
}
ARM_ORDER = ("prior_work_style", "sticks_without_admission", "sticks_admitted")


def format_percentage(rate: float) -> str:
    """Present a frozen unit-interval rate as a percentage."""
    return f"{100 * rate:.1f}"


def load_analysis(experiment_id: str) -> dict:
    return json.loads((COMPARISON_ROOT / experiment_id / "analysis.json").read_text())


def arm_row(analysis: dict, arm: str) -> dict:
    return next(row for row in analysis["overall"] if row["arm"] == arm)


def render_table(first: dict, second: dict) -> str:
    lines = [
        "% Generated by scripts/render_admission_comparison_table.py from frozen evidence.",
        r"\begin{tabular}{@{}lcrrrr@{}}",
        r"\toprule",
        r" & & \multicolumn{2}{c}{\textbf{Admitted / emitted (\%)}} & \multicolumn{2}{c}{\textbf{Abstention (\%)}} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
        r"\textbf{Input} & \textbf{Admit} & \textbf{M1} & \textbf{M2} & \textbf{M1} & \textbf{M2} \\",
        r"\midrule",
    ]
    for arm in ARM_ORDER:
        _, admission = ARM_DESIGN[arm]
        left, right = arm_row(first, arm), arm_row(second, arm)
        lines.append(
            f"{ARM_LABEL[arm]} & {admission} & "
            f"{format_percentage(left['validity_rate'])} & {format_percentage(right['validity_rate'])} & "
            f"{format_percentage(left['abstention_rate'])} & {format_percentage(right['abstention_rate'])} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def render_macros(first: dict, second: dict) -> str:
    admitted_first = arm_row(first, "sticks_admitted")
    admitted_second = arm_row(second, "sticks_admitted")
    prior_first = arm_row(first, "prior_work_style")
    prior_second = arm_row(second, "prior_work_style")
    gap_first = first["validity_gap_vs_admitted"]["prior_work_style"]
    gap_second = second["validity_gap_vs_admitted"]["prior_work_style"]
    profile_first = first["abstention_profile"]
    profile_second = second["abstention_profile"]

    macros = {
        "admissionObservations": str(first["observations"] + second["observations"]),
        "admissionSeeds": "5",
        "admissionModels": "2",
        "admittedValidityFirst": format_percentage(admitted_first["validity_rate"]),
        "admittedValiditySecond": format_percentage(admitted_second["validity_rate"]),
        "priorValidityFirst": format_percentage(prior_first["validity_rate"]),
        "priorValiditySecond": format_percentage(prior_second["validity_rate"]),
        "admittedAbstentionFirst": format_percentage(admitted_first["abstention_rate"]),
        "admittedAbstentionSecond": format_percentage(admitted_second["abstention_rate"]),
        "admissionGapFirst": format_percentage(gap_first["mean_gap"]),
        "admissionGapFirstLow": format_percentage(gap_first["ci_low"]),
        "admissionGapFirstHigh": format_percentage(gap_first["ci_high"]),
        "admissionGapSecond": format_percentage(gap_second["mean_gap"]),
        "admissionGapSecondLow": format_percentage(gap_second["ci_low"]),
        "admissionGapSecondHigh": format_percentage(gap_second["ci_high"]),
        "justifiedShareFirst": format_percentage(profile_first["justified_share"]),
        "justifiedShareSecond": format_percentage(profile_second["justified_share"]),
        "justifiedAbstentionsFirst": str(profile_first["justified_no_admissible_realization"]),
        "justifiedAbstentionsSecond": str(profile_second["justified_no_admissible_realization"]),
    }
    header = [
        "% Generated by scripts/render_admission_comparison_table.py from frozen evidence.",
        "% Do not edit: regenerate with scripts/reproduce.py.",
    ]
    body = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros.items()]
    return "\n".join(header + body) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--first-experiment", default="2026-09-07-local")
    parser.add_argument("--second-experiment", default="2026-09-07-qwen14b")
    parser.add_argument(
        "--output-dir",
        default=str(PROJECT_ROOT / "release" / "experiments" / "admission_comparison"),
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    first = load_analysis(args.first_experiment)
    second = load_analysis(args.second_experiment)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "admission_table.tex").write_text(render_table(first, second), encoding="utf-8")
    MACROS_OUTPUT.write_text(render_macros(first, second), encoding="utf-8")
    print(f"wrote {output_dir / 'admission_table.tex'}")
    print(f"wrote {MACROS_OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
