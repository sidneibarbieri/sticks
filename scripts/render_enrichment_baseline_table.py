#!/usr/bin/env python3
"""Render the raw-STIX-versus-enriched baseline table from the frozen baseline evidence.

Reads release/experiments/enrichment_baseline/*.baseline.json and emits a LaTeX and a
Markdown table. The script only formats already-frozen records; it does not recompute them.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DIR = PROJECT_ROOT / "release" / "experiments" / "enrichment_baseline"
DEFAULT_CAMPAIGNS = ("C0010", "C0026", "C0045")

HEADERS = ("Campaign", "Steps", "Raw STIX exec.", "Enriched exec.", "Enrichment gain")


def _load(directory: Path, campaign_id: str) -> dict:
    return json.loads(
        (directory / f"{campaign_id}.baseline.json").read_text(encoding="utf-8")
    )


def _cells(record: dict) -> list[str]:
    total = record["total_steps"]
    raw = record["raw_stix_executable_steps"]
    enriched = record["enriched_executable_steps"]
    return [
        record["campaign_id"],
        str(total),
        f"{raw}/{total}",
        f"{enriched}/{total}",
        f"+{record['enrichment_delta']}",
    ]


def render_latex(records: list[dict]) -> str:
    lines = [
        "% Generated by scripts/render_enrichment_baseline_table.py from frozen evidence.",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        r"\textbf{Campaign} & \textbf{Steps} & \textbf{Raw STIX} & \textbf{Enriched} & \textbf{Gain} \\",
        "\\midrule",
    ]
    lines += [" & ".join(_cells(record)) + " \\\\" for record in records]
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def render_markdown(records: list[dict]) -> str:
    lines = [
        "<!-- Generated from frozen enrichment-baseline evidence. -->",
        "| " + " | ".join(HEADERS) + " |",
        "|" + "|".join(["---"] * len(HEADERS)) + "|",
    ]
    lines += ["| " + " | ".join(_cells(record)) + " |" for record in records]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaigns", nargs="+", default=list(DEFAULT_CAMPAIGNS))
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args()

    records = [_load(args.input_dir, campaign_id) for campaign_id in args.campaigns]
    (args.output_dir / "baseline_table.tex").write_text(render_latex(records), encoding="utf-8")
    (args.output_dir / "baseline_table.md").write_text(render_markdown(records), encoding="utf-8")
    print(render_markdown(records))
    print(f"[baseline-table] wrote baseline_table.tex and baseline_table.md to {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
