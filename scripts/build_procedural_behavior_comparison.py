#!/usr/bin/env python3
"""Emit the procedural-behavior comparison from the checkable definition.

Applies the ``assess_element`` predicate to canonical representatives of each
representation -- a TTP, a MITRE Attack Flow node, and a real STICKS concretized step --
and writes a frozen comparison record plus a LaTeX/Markdown table. The comparison is thus
generated from the definition, not asserted by hand. The Attack Flow and TTP component
profiles are modeling claims stated in DEFINITION.md; the STICKS row is a real step.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = PROJECT_ROOT / "src"
for import_root in (PROJECT_ROOT, SRC_ROOT):
    if str(import_root) not in sys.path:
        sys.path.insert(0, str(import_root))

from concretization.models import ActionTemplate, BindingCatalog  # noqa: E402
from concretization.pipeline import concretize_plan  # noqa: E402
from contracts.procedural_behavior import (  # noqa: E402
    REQUIRED_COMPONENTS,
    assess_element,
)
from contracts.procedural_ir import ProceduralPlan  # noqa: E402

PLANS_DIR = PROJECT_ROOT / "release" / "plans"
TEMPLATES_PATH = PROJECT_ROOT / "data" / "concretization" / "action_templates.json"
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "release" / "experiments" / "procedural_behavior"

TTP_ELEMENT = {"technique_id": "T1059.006"}
ATTACK_FLOW_ELEMENT = {
    "technique_id": "T1059.006",
    "sequence": 3,
    "requires": ["prior_access"],
    "produces": ["code_execution"],
}


def _sticks_step(campaign_id: str) -> dict:
    plan = ProceduralPlan.model_validate_json(
        (PLANS_DIR / f"{campaign_id}.procedural-plan.json").read_text(encoding="utf-8")
    )
    catalog = BindingCatalog.model_validate_json(
        (PLANS_DIR / f"{campaign_id}.binding-catalog.json").read_text(encoding="utf-8")
    )
    templates = [
        ActionTemplate.model_validate(item)
        for item in json.loads(TEMPLATES_PATH.read_text(encoding="utf-8"))["templates"]
    ]
    result = concretize_plan(plan, catalog, templates, llm_proposals=[])
    return result.model_dump(mode="json")["steps"][0]


def _mark(present: bool) -> str:
    return "yes" if present else "no"


def build_comparison(campaign_id: str) -> dict:
    representations = {
        "TTP (ATT&CK technique in STIX)": TTP_ELEMENT,
        "MITRE Attack Flow node": ATTACK_FLOW_ELEMENT,
        "STICKS procedural behavior": _sticks_step(campaign_id),
    }
    rows = {}
    for name, element in representations.items():
        assessment = assess_element(element)
        present = {c.value for c in assessment.present}
        rows[name] = {
            "components": {c.value: (c.value in present) for c in REQUIRED_COMPONENTS},
            "is_procedural_behavior": assessment.is_procedural_behavior,
        }
    return {"sticks_source_campaign": campaign_id, "representations": rows}


def render_markdown(comparison: dict) -> str:
    components = [c.value for c in REQUIRED_COMPONENTS]
    headers = ["Representation", *components, "Procedural behavior"]
    lines = [
        "<!-- Generated by scripts/build_procedural_behavior_comparison.py from the checkable definition. -->",
        "| " + " | ".join(headers) + " |",
        "|" + "|".join(["---"] * len(headers)) + "|",
    ]
    for name, row in comparison["representations"].items():
        cells = [name] + [_mark(row["components"][c]) for c in components]
        cells.append(_mark(row["is_procedural_behavior"]))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaign", default="C0045")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)
    comparison = build_comparison(args.campaign)
    (args.output_dir / "comparison.json").write_text(
        json.dumps(comparison, indent=2) + "\n", encoding="utf-8"
    )
    (args.output_dir / "comparison_table.md").write_text(
        render_markdown(comparison), encoding="utf-8"
    )
    print(render_markdown(comparison))
    print(f"[procedural-behavior] wrote comparison.json and comparison_table.md to {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
