#!/usr/bin/env python3
"""Derive, per template, why its fidelity ceiling is adapted or inspired.

The distinction is not a label an author assigns by taste: it follows from what the template's
evidence obligations commit to. A template whose evidence records an observable effect on a lab
object performs the mechanism against benign resources and is adapted. A template whose evidence
records only a description, plus an explicit statement that the real mechanism did not occur,
represents the condition instead of performing it and is inspired.

Emitting this from the catalog keeps the appendix table and the artifact from drifting apart.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
TEMPLATES_PATH = PROJECT_ROOT / "data" / "concretization" / "action_templates.json"
MACROS_OUTPUT = PROJECT_ROOT / "release" / "fidelity_macros.tex"

# Evidence that an effect was produced and observed on a declared lab object.
PERFORMED_EVIDENCE = {
    "process_exit_recorded",
    "stdout_hash_recorded",
    "artifact_hash_recorded",
    "archive_hash_recorded",
    "service_request_logged",
    "http_request_logged",
    "http_status_recorded",
    "resolver_query_logged",
    "bounded_effect_observed",
    "file_count_recorded",
    # Deleting an artifact is itself an observable mutation, evidenced by recording its absence.
    "file_absence_recorded",
    "bytes_transferred_recorded",
    "destination_hash_recorded",
    "source_and_destination_hashes_match",
    "source_and_encoded_hashes_recorded",
    "interface_snapshot_recorded",
    "duration_and_cpu_bound_recorded",
    "staging_path_recorded",
    "web_asset_hash_recorded",
    "chunk_manifest_recorded",
    "collection_manifest_recorded",
    "fixture_access_logged",
    "fixture_hash_recorded",
    "input_manifest_recorded",
}


def non_occurrence_predicates(evidence: list[str]) -> list[str]:
    """Evidence asserting that the real-world harmful behavior did not happen."""
    return sorted(item for item in evidence if item.startswith("no_") or item.startswith("external_"))


def performed_predicates(evidence: list[str]) -> list[str]:
    return sorted(item for item in evidence if item in PERFORMED_EVIDENCE)


def classify(template: dict) -> dict[str, object]:
    evidence = list(template["evidence_predicates"])
    performed = performed_predicates(evidence)
    withheld = non_occurrence_predicates(evidence)
    return {
        "template_id": template["template_id"],
        "technique_ids": sorted(template["technique_ids"]),
        "fidelity_ceiling": template["fidelity_ceiling"],
        "declared_evidence_predicates": sorted(evidence),
        "performs_observable_effect": bool(performed),
        "observed_evidence": performed,
        "non_occurrence_guarantees": withheld,
        "description": template["description"],
    }


def summarize(rows: list[dict]) -> dict[str, object]:
    by_tier: dict[str, int] = {}
    for row in rows:
        by_tier[row["fidelity_ceiling"]] = by_tier.get(row["fidelity_ceiling"], 0) + 1
    adapted_performing = sum(
        1 for row in rows if row["fidelity_ceiling"] == "adapted" and row["performs_observable_effect"]
    )
    inspired_performing = sum(
        1 for row in rows if row["fidelity_ceiling"] == "inspired" and row["performs_observable_effect"]
    )
    return {
        "templates": len(rows),
        "by_tier": by_tier,
        "adapted_that_perform_an_observable_effect": adapted_performing,
        "inspired_that_perform_an_observable_effect": inspired_performing,
        "templates_with_non_occurrence_guarantees": sum(
            1 for row in rows if row["non_occurrence_guarantees"]
        ),
    }


def latex_table(rows: list[dict]) -> str:
    lines = [
        r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{0.29\textwidth}>{\centering\arraybackslash}p{0.12\textwidth}>{\centering\arraybackslash}p{0.11\textwidth}L@{}}",
        r"\toprule",
        r"\textbf{Template} & \textbf{Technique} & \textbf{Ceiling} & \textbf{Declared evidence predicates} \\",
        r"\midrule",
    ]
    for row in sorted(rows, key=lambda item: (item["fidelity_ceiling"], item["template_id"])):
        evidence = ", ".join(row["declared_evidence_predicates"])
        lines.append(
            f"{row['template_id'].replace('_', '-')} & "
            f"{', '.join(row['technique_ids'])} & "
            f"{row['fidelity_ceiling']} & "
            f"{evidence.replace('_', '-')} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabularx}"]
    return "\n".join(lines)


def render_macros(summary: dict[str, object]) -> str:
    by_tier = summary["by_tier"]
    lines = [
        "% Generated by scripts/build_fidelity_rationale.py from frozen evidence.",
        "% Do not edit: regenerate with scripts/reproduce.py.",
        f"\\newcommand{{\\adaptedTemplateCount}}{{{by_tier.get('adapted', 0)}}}",
        f"\\newcommand{{\\inspiredTemplateCount}}{{{by_tier.get('inspired', 0)}}}",
        f"\\newcommand{{\\catalogTemplateCount}}{{{summary['templates']}}}",
    ]
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir", default=str(PROJECT_ROOT / "release" / "experiments" / "fidelity_rationale")
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    templates = json.loads(TEMPLATES_PATH.read_text())["templates"]
    rows = [classify(template) for template in templates]
    summary = summarize(rows)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "fidelity_rationale.json").write_text(
        json.dumps({"summary": summary, "templates": rows}, indent=2) + "\n"
    )
    (output_dir / "fidelity_rationale.tex").write_text(latex_table(rows) + "\n")
    MACROS_OUTPUT.write_text(render_macros(summary), encoding="utf-8")

    print(json.dumps(summary, indent=2))
    for row in rows:
        if row["fidelity_ceiling"] == "inspired":
            print(
                f"  inspired: {row['template_id']:38} performs_effect={row['performs_observable_effect']} "
                f"withheld={row['non_occurrence_guarantees']}"
            )
    print(f"\nwrote {output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
