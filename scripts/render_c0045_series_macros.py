#!/usr/bin/env python3
"""Render the paper macros for the C0045 observer calibration from its archive.

The archive is replayed first; numbers are read only from an archive that
passes the offline verifier.
"""

from __future__ import annotations

import argparse
import json
import sys
import tarfile
from collections.abc import Iterable, Mapping
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = (str(PROJECT_ROOT / "src"), str(PROJECT_ROOT))

from runners.c0045_effect_series import CONTROL_ARMS, load_c0045_effect_series  # noqa: E402
from scripts.verify_c0045_effect_series_archive import (  # noqa: E402
    series_path_for_archive,
    verify_archive,
)

MACRO_PREFIX = {
    "treatment": "Treatment",
    "busy": "Busy",
    "idle": "Idle",
    "controller_only": "Controller",
}


def _values(record: object, key: str) -> Iterable[object]:
    if isinstance(record, dict):
        for name, value in record.items():
            if name == key:
                yield value
            yield from _values(value, key)
    elif isinstance(record, list):
        for value in record:
            yield from _values(value, key)


def _single(record: object, key: str) -> int:
    values = list(_values(record, key))
    if len(set(values)) != 1 or not isinstance(values[0], int):
        raise ValueError(f"C0045 summary must carry exactly one {key}")
    return values[0]


def cell_deltas(
    archive_path: Path, series_root: str
) -> tuple[dict[str, tuple[str, int]], int]:
    """Map each cell to its arm and CPU delta; return the preregistered threshold."""
    with tarfile.open(archive_path, "r:gz") as archive:
        def load(name: str) -> object:
            member = archive.extractfile(name.removeprefix("./"))
            if member is None:
                raise ValueError(f"C0045 archive lacks {name}")
            return json.loads(member.read())

        outcomes = sorted(
            name for name in archive.getnames()
            if name.startswith(f"{series_root}/") and name.endswith("/outcome.json")
        )
        cells: dict[str, tuple[str, int]] = {}
        thresholds: set[int] = set()
        for name in outcomes:
            outcome = load(name)
            summary = load(f"{outcome['run_relative_path']}/summary.json")
            cells[outcome["cell_id"]] = (
                outcome["arm"], _single(summary, "cpu_ticks_delta")
            )
            if outcome["arm"] == "treatment":
                thresholds.add(_single(summary, "minimum_cpu_ticks"))
    if len(thresholds) != 1:
        raise ValueError("C0045 treatment cells must share one threshold")
    return cells, thresholds.pop()


def summarize(cells: Mapping[str, tuple[str, int]], threshold: int) -> dict[str, int]:
    """Reduce per-cell deltas to the counts and ranges the paper states."""
    macros = {"Cells": len(cells), "Threshold": threshold}
    for arm in CONTROL_ARMS:
        deltas = [delta for cell_arm, delta in cells.values() if cell_arm == arm]
        if not deltas:
            raise ValueError(f"C0045 archive has no {arm} cell")
        prefix = MACRO_PREFIX[arm]
        macros[f"{prefix}N"] = len(deltas)
        macros[f"{prefix}Min"] = min(deltas)
        macros[f"{prefix}Max"] = max(deltas)
        macros[f"{prefix}Above"] = sum(delta >= threshold for delta in deltas)
    return macros


def render(macros: Mapping[str, int], archive_sha256: str) -> str:
    lines = [
        "% Generated by scripts/render_c0045_series_macros.py; do not edit.",
        f"% C0045 effect-series archive SHA-256: {archive_sha256}",
    ]
    lines += [
        f"\\newcommand{{\\cxs{name}}}{{{value}}}" for name, value in macros.items()
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True, type=Path)
    parser.add_argument("--output", type=Path)
    options = parser.parse_args()
    audit = verify_archive(options.archive)
    if audit.failed or audit.runner_errors or audit.boot_reused:
        raise ValueError("C0045 archive replay reports an unusable cell")
    series_root = load_c0045_effect_series(
        series_path_for_archive(options.archive)
    ).receipt_root_name
    cells, threshold = cell_deltas(options.archive, series_root)
    text = render(summarize(cells, threshold), audit.archive_sha256)
    if options.output is None:
        sys.stdout.write(text)
    else:
        options.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
