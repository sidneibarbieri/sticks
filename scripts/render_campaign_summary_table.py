#!/usr/bin/env python3
"""Render one row per deep-slice campaign from the frozen baseline, provenance,
and commitment records.

The three records are also rendered separately; this table joins them so a reader
sees each campaign once. It formats frozen values only.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field, model_validator

PROJECT_ROOT = Path(__file__).resolve().parents[1]
EXPERIMENTS = PROJECT_ROOT / "release" / "experiments"
DEFAULT_CAMPAIGNS = ("C0010", "C0026", "C0045")
DEFAULT_OUTPUT = EXPERIMENTS / "campaign_summary"


class CampaignSummaryRow(BaseModel):
    """The admission, provenance, and commitment outcome of one campaign."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    campaign_id: str
    steps: int = Field(gt=0)
    raw_admitted: int = Field(ge=0)
    enriched_admitted: int = Field(ge=0)
    bindings: int = Field(ge=0)
    cti_bindings: int = Field(ge=0)
    environment_bindings: int = Field(ge=0)
    system_bindings: int = Field(ge=0)
    mechanism_commitments: int = Field(ge=0)
    binding_commitments: int = Field(ge=0)
    pruned_candidates: int = Field(ge=0)

    @model_validator(mode="after")
    def check_consistency(self) -> CampaignSummaryRow:
        provenance_total = self.cti_bindings + self.environment_bindings + self.system_bindings
        if provenance_total != self.bindings:
            raise ValueError(f"{self.campaign_id}: binding provenance does not sum to the total")
        if max(self.raw_admitted, self.enriched_admitted) > self.steps:
            raise ValueError(f"{self.campaign_id}: more admitted steps than steps")
        return self

    @property
    def commitments(self) -> int:
        return self.mechanism_commitments + self.binding_commitments

    @classmethod
    def from_records(cls, baseline: dict, provenance: dict, commitments: dict) -> CampaignSummaryRow:
        identities = {baseline["campaign_id"], provenance["campaign_id"], commitments["campaign_id"]}
        if len(identities) != 1:
            raise ValueError(f"records describe different campaigns: {sorted(identities)}")
        occurrences = provenance["binding_occurrence_counts"]
        return cls(
            campaign_id=baseline["campaign_id"],
            steps=baseline["total_steps"],
            raw_admitted=baseline["raw_stix_executable_steps"],
            enriched_admitted=baseline["enriched_executable_steps"],
            bindings=provenance["total_binding_occurrences"],
            cti_bindings=occurrences["cti_evidenced"],
            environment_bindings=occurrences["environment_determined"],
            system_bindings=occurrences["system_introduced"],
            mechanism_commitments=commitments["mechanism_commitments"],
            binding_commitments=commitments["binding_commitments"],
            pruned_candidates=commitments["candidates_pruned_by_verifier"],
        )


def load_row(experiments: Path, campaign_id: str) -> CampaignSummaryRow:
    def record(kind: str, suffix: str) -> dict:
        path = experiments / kind / f"{campaign_id}.{suffix}.json"
        return json.loads(path.read_text(encoding="utf-8"))

    return CampaignSummaryRow.from_records(
        baseline=record("enrichment_baseline", "baseline"),
        provenance=record("provenance", "provenance"),
        commitments=record("execution_commitments", "commitments"),
    )


def _cells(campaign: str, steps: int, raw: int, enriched: int, counts: list[int]) -> list[str]:
    return [campaign, str(steps), f"{raw}/{steps}", f"{enriched}/{steps}", *map(str, counts)]


def _row_cells(row: CampaignSummaryRow) -> list[str]:
    counts = [row.bindings, row.cti_bindings, row.environment_bindings, row.system_bindings,
              row.commitments, row.pruned_candidates]
    return _cells(row.campaign_id, row.steps, row.raw_admitted, row.enriched_admitted, counts)


def _total_cells(rows: list[CampaignSummaryRow]) -> list[str]:
    per_row = [
        [row.bindings, row.cti_bindings, row.environment_bindings, row.system_bindings,
         row.commitments, row.pruned_candidates]
        for row in rows
    ]
    counts = [sum(column) for column in zip(*per_row)]
    return _cells(
        "Total",
        sum(row.steps for row in rows),
        sum(row.raw_admitted for row in rows),
        sum(row.enriched_admitted for row in rows),
        counts,
    )


def render_latex(rows: list[CampaignSummaryRow]) -> str:
    lines = [
        "% Generated by scripts/render_campaign_summary_table.py from frozen evidence.",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrrrr@{}}",
        r"\toprule",
        r" & & \multicolumn{2}{c}{\textbf{Admitted steps}} & \multicolumn{4}{c}{\textbf{Binding provenance}}"
        r" & \multicolumn{2}{c}{\textbf{Commitments}} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-8}\cmidrule(lr){9-10}",
        r"\textbf{Campaign} & \textbf{Steps} & \textbf{Raw STIX} & \textbf{Enriched} & \textbf{Total}"
        r" & \textbf{CTI} & \textbf{Env.} & \textbf{System} & \textbf{Explicit} & \textbf{Pruned} \\",
        r"\midrule",
    ]
    lines += [" & ".join(_row_cells(row)) + r" \\" for row in rows]
    lines += [r"\midrule", " & ".join(_total_cells(rows)) + r" \\", r"\bottomrule", r"\end{tabular*}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaigns", nargs="+", default=list(DEFAULT_CAMPAIGNS))
    parser.add_argument("--experiments-dir", type=Path, default=EXPERIMENTS)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    rows = [load_row(args.experiments_dir, campaign_id) for campaign_id in args.campaigns]
    args.output_dir.mkdir(parents=True, exist_ok=True)
    output = args.output_dir / "campaign_summary_table.tex"
    output.write_text(render_latex(rows), encoding="utf-8")
    print(f"[campaign-summary] wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
